-- Schema documentation for the Go rewrite.
--
-- The database is FROZEN. The C# service owns it, uses it in production, and
-- holds roughly 4,000 images, so no table, column or type may change as part of
-- the rewrite. This file documents what the Go side reads and writes; the
-- authoritative definition remains the EF Core model snapshot at
-- backend/WaifuApi.Infrastructure/Persistence/Migrations/WaifuDbContextModelSnapshot.cs.
--
-- Two details matter more than the rest and are easy to get wrong:
--
--   1. Images.PerceptualHash is bit(64), not text or bigint. The Go service
--      reads it as a 64-bit Postgres bit string and compares it with the
--      pgvector-style Hamming distance operator.
--
--   2. Identity columns are bigint GENERATED BY DEFAULT AS IDENTITY, so a test
--      can insert explicit IDs when seeding fixtures.

CREATE TABLE IF NOT EXISTS "User" (
    "Id"                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DiscordId"         text        NOT NULL,
    "Name"              text        NOT NULL,
    "AvatarUrl"         text        NULL,
    "Role"              integer     NOT NULL DEFAULT 0,
    "RequestCount"      bigint      NOT NULL DEFAULT 0,
    "JwtRequestCount"   bigint      NOT NULL DEFAULT 0,
    "ApiKeyRequestCount" bigint     NOT NULL DEFAULT 0,
    "IsBlacklisted"     boolean     NOT NULL DEFAULT false,
    "BlacklistReason"   text        NULL
);

-- Role values are compared with >= throughout the authorisation code:
--   0 User, 1 TrustedUser, 2 Moderator, 3 Admin
-- The column is left unconstrained on purpose, matching the C# service, so a
-- role can be added without a migration. The Go side rejects unknown values at
-- parse time instead.
CREATE TABLE IF NOT EXISTS "Image" (
    "Id"            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UploaderId"    bigint      NULL REFERENCES "User"("Id"),
    "Width"         bigint      NOT NULL,
    "Height"        bigint      NOT NULL,
    "ByteSize"      bigint      NOT NULL,
    "Extension"     text        NOT NULL,
    "DominantColor" text        NOT NULL,
    "Source"        text        NULL,
    "IsNsfw"        boolean     NOT NULL DEFAULT false,
    "IsAnimated"    boolean     NOT NULL DEFAULT false,
    "UploadedAt"    timestamptz NOT NULL DEFAULT now(),

    -- Duplicate detection compares this against incoming uploads at Hamming
    -- distance <= 4. See PLAN.md section 6.1: existing values were produced by
    -- an algorithm that does not reproduce itself, so a backfill is required
    -- before this column can be trusted to be consistent.
    "PerceptualHash" bit(64)     NOT NULL,

    -- 0 Pending, 1 Accepted. There is no Rejected value: a rejected image row
    -- is deleted, not flagged.
    "ReviewStatus"  integer     NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS "Tag" (
    "Id"          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name"        text        NOT NULL,
    "Slug"        text        NOT NULL UNIQUE,
    "Description" text        NOT NULL DEFAULT '',
    "CreatorId"   bigint      NULL REFERENCES "User"("Id"),
    "ReviewStatus" integer    NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS "Artist" (
    "Id"           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name"         text        NOT NULL,
    "DeviantArt"   text        NULL,
    "Twitter"      text        NULL,
    "Patreon"      text        NULL,
    "Pixiv"        text        NULL,
    "CreatorId"    bigint      NULL REFERENCES "User"("Id"),
    "ReviewStatus" integer     NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS "ImageTag" (
    "ImageId" bigint NOT NULL REFERENCES "Image"("Id") ON DELETE CASCADE,
    "TagId"   bigint NOT NULL REFERENCES "Tag"("Id")   ON DELETE CASCADE,
    PRIMARY KEY ("ImageId", "TagId")
);

CREATE TABLE IF NOT EXISTS "ArtistImage" (
    "ImageId"  bigint NOT NULL REFERENCES "Image"("Id")  ON DELETE CASCADE,
    "ArtistId" bigint NOT NULL REFERENCES "Artist"("Id") ON DELETE CASCADE,
    PRIMARY KEY ("ImageId", "ArtistId")
);

CREATE TABLE IF NOT EXISTS "Album" (
    "Id"          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"      bigint  NOT NULL REFERENCES "User"("Id") ON DELETE CASCADE,
    "Name"        text    NOT NULL,
    "Description" text    NOT NULL DEFAULT '',
    "IsDefault"   boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS "AlbumItem" (
    "AlbumId" bigint      NOT NULL REFERENCES "Album"("Id") ON DELETE CASCADE,
    "ImageId" bigint      NOT NULL REFERENCES "Image"("Id") ON DELETE CASCADE,
    "AddedAt" timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY ("AlbumId", "ImageId")
);

-- Only the hash of an API key is stored. The plaintext is shown once at
-- creation and cannot be recovered.
CREATE TABLE IF NOT EXISTS "ApiKey" (
    "Id"             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"         bigint      NOT NULL REFERENCES "User"("Id") ON DELETE CASCADE,
    "Description"    text        NOT NULL,
    "KeyHash"        text        NOT NULL,
    "CreatedAt"      timestamptz NOT NULL DEFAULT now(),
    "LastUsedAt"     timestamptz NULL,
    "ExpirationDate" timestamptz NULL
);

CREATE TABLE IF NOT EXISTS "Report" (
    "Id"           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"       bigint      NOT NULL REFERENCES "User"("Id"),
    "ImageId"      bigint      NULL REFERENCES "Image"("Id"),
    "Description"  text        NOT NULL,
    "Status"       integer     NOT NULL DEFAULT 0,
    "ReviewerNote" text        NULL,
    "CreatedAt"    timestamptz NOT NULL DEFAULT now()
);

-- Kind:       0 NewContent, 1 Edit
-- TargetType: 0 Image, 1 Tag, 2 Artist
-- Status:     0 Pending, 1 Approved, 2 Rejected, 3 Cancelled
CREATE TABLE IF NOT EXISTS "ReviewTask" (
    "Id"                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Kind"              integer     NOT NULL,
    "TargetType"        integer     NOT NULL,
    "TargetId"          bigint      NOT NULL,
    "SubmitterId"       bigint      NULL REFERENCES "User"("Id"),
    "Payload"           jsonb       NOT NULL DEFAULT '{}'::jsonb,
    "Reason"            text        NOT NULL DEFAULT '',
    "Status"            integer     NOT NULL DEFAULT 0,
    "ReviewerNote"      text        NOT NULL DEFAULT '',
    "ReviewerId"        bigint      NULL REFERENCES "User"("Id"),
    "ModeratorEditedAt" timestamptz NULL,
    "CreatedAt"         timestamptz NOT NULL DEFAULT now(),
    "ResolvedAt"        timestamptz NULL
);

-- Variant: 0 Info, 1 Success, 2 Warning, 3 Danger
--
-- GET /banner answers 204 when there is no row or the row is disabled. The
-- frontend hook depends on that distinction, so it must be preserved exactly.
CREATE TABLE IF NOT EXISTS "SiteBanner" (
    "Id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Message"    text        NOT NULL,
    "Variant"    integer     NOT NULL DEFAULT 0,
    "IsEnabled"  boolean     NOT NULL DEFAULT false,
    "UpdatedAt"  timestamptz NOT NULL DEFAULT now(),
    "UpdatedById" bigint     NULL REFERENCES "User"("Id")
);

CREATE TABLE IF NOT EXISTS "DailyStat" (
    "Id"           integer NOT NULL,
    "Date"         date    NOT NULL,
    "RequestCount" integer NOT NULL DEFAULT 0,
    PRIMARY KEY ("Id")
);

CREATE TABLE IF NOT EXISTS "GlobalStat" (
    "Key"   text   PRIMARY KEY,
    "Value" bigint NOT NULL DEFAULT 0
);

-- ---------------------------------------------------------------------------
-- Indexes matching the query patterns the API relies on.
-- ---------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS "IX_Image_ReviewStatus_UploadedAt"
    ON "Image" ("ReviewStatus", "UploadedAt" DESC);
CREATE INDEX IF NOT EXISTS "IX_Image_Width" ON "Image" ("Width");
CREATE INDEX IF NOT EXISTS "IX_Image_Height" ON "Image" ("Height");
CREATE INDEX IF NOT EXISTS "IX_Image_ByteSize" ON "Image" ("ByteSize");
CREATE INDEX IF NOT EXISTS "IX_Image_IsNsfw" ON "Image" ("IsNsfw");
CREATE INDEX IF NOT EXISTS "IX_Image_IsAnimated" ON "Image" ("IsAnimated");

CREATE INDEX IF NOT EXISTS "IX_ImageTag_TagId" ON "ImageTag" ("TagId");
CREATE INDEX IF NOT EXISTS "IX_ArtistImage_ArtistId" ON "ArtistImage" ("ArtistId");
CREATE INDEX IF NOT EXISTS "IX_ReviewTask_Status_CreatedAt"
    ON "ReviewTask" ("Status", "CreatedAt" DESC);
CREATE INDEX IF NOT EXISTS "IX_ReviewTask_SubmitterId" ON "ReviewTask" ("SubmitterId");
CREATE INDEX IF NOT EXISTS "IX_ApiKey_KeyHash" ON "ApiKey" ("KeyHash");
CREATE INDEX IF NOT EXISTS "IX_Report_Status_CreatedAt"
    ON "Report" ("Status", "CreatedAt" DESC);